function fold(s: string) {
  return s
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^0-9a-zа-я\s]+/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function extractDish(q: string): string {
  const m = q.match(
    /(?:рецепт|приготовить|приготовление|как сделать|как варить|как пожарить|как жарить)\s+(.+)/i,
  );
  if (m?.[1]) return m[1].replace(/\s+/g, " ").trim();
  return "";
}

