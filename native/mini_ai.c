static void mini_fold(wchar_t *s) {
  for (wchar_t *p = s; *p; p++) {
    wchar_t c = *p;
    if (c >= L'A' && c <= L'Z') c = (wchar_t)(c - L'A' + L'a');
    if (c >= 0x410 && c <= 0x42F) c = (wchar_t)(c + 0x20);
    if (c == 0x401 || c == 0x451) c = 0x435; /* ё → е */
    if (c == L'\r' || c == L'\n' || c == L'\t' || c == L',' || c == L'.' || c == L'?' ||
        c == L'!' || c == L':' || c == L';' || c == L'«' || c == L'»' || c == L'"')
      c = L' ';
    *p = c;
  }
}

static int mini_score(const wchar_t *q, const wchar_t *keys) {
  int score = 0;
  const wchar_t *p = keys;
  while (*p) {
    while (*p == L' ') p++;
    const wchar_t *start = p;
    while (*p && *p != L' ') p++;
    int n = (int)(p - start);
    if (n <= 0) continue;
    wchar_t tok[80];
    if (n > 79) n = 79;
    memcpy(tok, start, (size_t)n * sizeof(wchar_t));
    tok[n] = 0;
    if (wcsstr(q, tok)) score += n >= 5 ? 3 : 2;
  }
  return score;
}

