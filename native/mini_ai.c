static void mini_fold(wchar_t *s) {
  for (wchar_t *p = s; *p; p++) {
    wchar_t c = *p;
    if (c >= L'A' && c <= L'Z') c = (wchar_t)(c - L'A' + L'a');
    if (c >= 0x410 && c <= 0x42F) c = (wchar_t)(c + 0x20);
    if (c == 0x401 || c == 0x451) c = 0x435; /* ё → е */
    if (c == L'\r' || c == L'\n' || c == L'\t' || c == L',' || c == L'.' || c == L'?' ||
        c == L'!' || c == L':' || c == L';' || c == L'«' || c == L'»' || c == L'"')
      c = L' ';
    *p = c;
  }
}

