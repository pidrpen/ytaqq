  tn_route(L"Планка", L"Полоса 22х110 ГОСТ 103-2006 / 45 ГОСТ 1050-2013", L"Ra 3,2\n§GB l=200 b=100 s=20\n", &r);
  nm_route(b, &r, L"3,1", L"норма: партия 20", &res);
