/* заводские пределы, без значений по умолчанию */
static void lim_factory(void) {
  for (int k = 0; k < NM_LIMS; k++) g_nmLim[k].min = g_nmLim[k].min0, g_nmLim[k].max = g_nmLim[k].max0, g_nmLim[k].def = NM_NONE;
}

static void test_formulas(void) {
  NmBase b;
  memset(&b, 0, sizeof(b));
  for (size_t i = 0; i < sizeof(kForm) / sizeof(kForm[0]); i++)
    if (!nm_base_add(&b, dupw(kForm[i][1]), kForm[i][0])) {
      g_fail++;
      printf("FAIL таблица формул %zu не прочиталась: ", i);
      out8(b.err);
      printf("\n");
    }
  ok("клетка «0,4–0,6» — середина", nm_val(L"0,4–0,6") == 0.5 && nm_isrange(L"0,4 - 0,6") && !nm_isrange(L"0,4"));
  ok("показатель «-0,9»", nm_val(L"-0,9") == -0.9 && nm_na(nm_val(L"-")) && nm_na(nm_val(L"—")));

  static TnRoute r;
  static NmResult res;
  /* вал Ø40 из круга 45, сталь 45: h = t = 2,5; S = середина 0,4–0,6 = 0,5 (ступень 0,5); T = 100;
     Cv 300, x 0,15, y 0,35, m 0,2; Kмv = (750/600)^1 = 1,25; Kφ 0,7 (угол 90), Kпv 0,9 (прокат) */
  route_one(&r, L"Токарная");
  r.cls = TN_ROT;
  r.s.mat = TNM_STEEL;
  tn_cpy(r.s.grade, 48, L"45");
  r.s.dmax = 40;
  tn_cpy(r.blank, TN_TXT, L"Круг 45 ГОСТ 2590");
  nm_route(&b, &r, NULL, L"норма: L 100", &res);
  show(&b, &res);
  const NmOp *o = &res.op[0];
  double V = 300 / (pow(100, 0.2) * pow(2.5, 0.15) * pow(0.5, 0.35)) * 1.25 * 0.7 * 0.9;
  near("V по формуле", nm_v(&o->c, L"V"), V);
  ok("n → ступень 630", 1000 * V / (NM_PI * 45) > 630 && 1000 * V / (NM_PI * 45) < 800);
  near("То = L/(n·S)", o->to, 100 / (630 * 0.5));
  has("подача — середина диапазона", o->how, L"S 0,5 мм/об — вид черновая, материал сталь, D 40, t 2,5 → табл. 3 поз. 1, «до 3», середина «0,4–0,6»");
  has("стойкость — середина", o->how, L"T (стойкость) 100 мин — инструмент твёрдый сплав → п. 4.1 поз. 1, середина «80–120»");
  has("коэффициенты строки", o->how, L"коэффициенты формулы: Cv 300, x 0,15, y 0,35, m 0,2 — материал сталь, инструмент твёрдый сплав, S 0,5 → табл. 7 поз. 2");
  has("Kмv по σв марки", o->how, L"Kмv = (750/σв)^nv = (750/600)^1 = 1,25 — σв 600 (по таблице: перечень материалов: ГОСТ (выдумано))");
  has("формула с числами", o->how, L"V = Cv/(T^m·t^x·S^y)·Kмv·Kv = 300/(100^0,2·2,5^0,15·0,5^0,35)·1,25·0,63 = ");
  has("инструмент по умолчанию", res.op[0].how, L"S по станку 0,5 → 0,5 (ступень 16К20");

  /* проходы: «проходов 2» — t = 2,5/2, i = 2; То вдвое (V по t 1,25 — другая, n своя) */
  nm_route(&b, &r, NULL, L"норма: L 100, проходов 2", &res);
  o = &res.op[0];
  near("t = h/проходов", nm_v(&o->c, L"t"), 1.25);
  near("i = 2", nm_v(&o->c, L"i"), 2);
  has("t — расчёт из проходов", o->how, L"t 1,25 мм (расчёт: припуск h/проходов) → проходов i = 2");

  /* параметры по операциям: L всем, подачи — своим операциям */
  r.n = 2;
  tn_cpy(r.op[1].op, 48, L"Сверлильная");
  r.s.holes = 2, r.s.holeMin = 8, r.s.thick = 0;
  /* номера — как в тексте маршрута: (место + 1)·5, здесь 005 и 010 */
  nm_route(&b, &r, NULL, L"норма: L 100, 005: подача 0,4, 010: подача 0,1, глубина 12", &res);
  ok("две операции", res.n == 2);
  near("005 — своя подача", nm_v(&res.op[0].c, L"S"), 0.4);
  near("010 — своя подача", nm_v(&res.op[1].c, L"S"), 0.1);
  near("L — обеим", nm_v(&res.op[1].c, L"L"), 100);
  ok("глубина 12 — не токарной", nm_na(nm_v(&res.op[0].c, L"l")));
  near("глубина 12 — сверлильной", nm_v(&res.op[1].c, L"l"), 12);

  /* сверление пластины Ст3сп: σв — середина 380–490 = 435, HB ≈ 435/3,4 = 128 → подача «до 160»
     0,29; T 25; Cv 9,8, q 0,4, y 0,5, m 0,2; Kмv = (750/435)^-0,9; Kзv 0,75 (одинарная заточка) */
  route_one(&r, L"Сверлильная");
  r.cls = TN_FLAT;
  r.s.mat = TNM_STEEL_PLAIN;
  tn_cpy(r.s.grade, 48, L"Ст3сп");
  r.s.thick = 6, r.s.holes = 4, r.s.holeMin = 10;
  r.blank[0] = 0;
  nm_route(&b, &r, NULL, NULL, &res);
  show(&b, &res);
  o = &res.op[0];
  double kmv = pow(750 / 435.0, -0.9);
  V = 9.8 * pow(10, 0.4) / (pow(25, 0.2) * pow(0.29, 0.5)) * kmv * 0.75;
  near("σв — середина диапазона", nm_v(&o->c, L"σв"), 435);
  near("HB — оценка по σв", nm_v(&o->c, L"HB"), 128);
  near("V сверления", nm_v(&o->c, L"V"), V);
  near("То сверления", o->to, 4 * 6 / (1000 * V / (NM_PI * 10) * 0.29));
  has("σв из перечня — середина", o->how, L"Kмv = (750/σв)^nv = (750/435)^-0,9 = ");
  has("одинарная заточка", o->how, L"Kv ×0,75 — заточка одинарная → табл. 18 поз. 2");
  has("Kмv — σв с источником", o->how, L"σв 435 (по таблице: перечень материалов, середина «380–490»");

  /* фрезерование корпуса из чугуна: Dф = ⌈1,375·80⌉ = 110, Sz — середина 0,14–0,24 по мощности 7,5;
     T задана 180; Kмv = (190/190)^1,25 = 1; Kпv 0,825 (отливка) */
  route_one(&r, L"Фрезерная");
  r.cls = TN_BODY;
  r.s.mat = TNM_IRON;
  tn_cpy(r.s.grade, 48, L"СЧ20");
  r.s.thick = 0, r.s.holes = 0;
  tn_cpy(r.blank, TN_TXT, L"Отливка");
  nm_route(&b, &r, NULL, L"норма: L 200, B 80, h 2, z 8, стойкость 180", &res);
  show(&b, &res);
  o = &res.op[0];
  V = 445 * pow(110, 0.2) / (pow(180, 0.32) * pow(2, 0.15) * pow(0.19, 0.35) * pow(80, 0.2)) * 0.825;
  double Sm = 0.19 * 8 * (1000 * V / (NM_PI * 110));
  near("Dф — оценка по B", nm_v(&o->c, L"Dф"), 110);
  near("V фрезерования", nm_v(&o->c, L"V"), V);
  near("То = L/Sм", o->to, 200 / Sm);
  has("Sz по мощности станка", o->how, L"Sz 0,19 мм/зуб — фреза торцовая, материал чугун, сплав ВК6, мощность 7,5 → табл. 22 поз. 1, «до 10», середина «0,14–0,24»");
  has("Sм = Sz·z·n", o->how, L"Sм = Sz·z·n = 0,19·8·");
  static wchar_t brief[4000];
  brief[0] = 0;
  nm_text_brief(&b, &res, L"", brief, 4000);
  has("строка режимов фрезерования", brief, L"\nРежимы: 005 V 120 · Sz 0,19 · t 2 · i 1 — изменить · подробно");
  has("T задана", o->how, L"T 180 мин (задано)");

  /* нет стойкости фрезы — в «Нет таблиц» и «Уточнить», То нет */
  nm_route(&b, &r, NULL, L"норма: L 200, B 80, h 2, z 8", &res);
  ok("без T фрезы То нет", nm_na(res.op[0].to));
  has("нет таблицы стойкости фрез", res.miss, L"фрезерная.стойкость");
  has("уточнить T", res.need, L"T — стойкость инструмента, мин");

  /* пределы и значения по умолчанию (Настройки → «Нормирование») */
  nm_lim(L"T")->def = 120; /* стойкость по умолчанию — вместо таблицы, которой нет */
  nm_route(&b, &r, NULL, L"норма: L 200, B 80, h 2, z 8", &res);
  ok("T по умолчанию — То есть", !nm_na(res.op[0].to));
  ok("с T по умолчанию нет пропуска таблицы", !wcsstr(res.miss, L"фрезерная.стойкость"));
  has("T — из Настроек", res.op[0].how, L"T 120 (по умолчанию: Настройки → Нормирование)");
  lim_factory();

  route_one(&r, L"Токарная");
  r.cls = TN_ROT;
  r.s.mat = TNM_STEEL;
  tn_cpy(r.s.grade, 48, L"45");
  r.s.dmax = 40;
  tn_cpy(r.blank, TN_TXT, L"Круг 45 ГОСТ 2590");
  nm_lim(L"V")->max = 80; /* формула даёт ~104 — берётся 80 */
  nm_route(&b, &r, NULL, L"норма: L 100", &res);
  o = &res.op[0];
  near("V ограничена пределом", nm_v(&o->c, L"V"), 80);
  has("строка предела V", o->how, L" → 80 (предел Настроек «Нормирование»: от 5 до 80 м/мин)");
  near("То — с V 80: n = 80000/(π·45) = 565,9 → 500", o->to, 100 / (500 * 0.5));
  lim_factory();
  nm_lim(L"i")->def = 2; /* проходов по умолчанию: t = 2,5/2 */
  nm_lim(L"партия")->def = 20;
  nm_route(&b, &r, NULL, L"норма: L 100", &res);
  o = &res.op[0];
  near("проходы по умолчанию — t = h/2", nm_v(&o->c, L"t"), 1.25);
  near("партия по умолчанию", nm_v(&o->c, L"партия"), 20);
  has("партия — из Настроек", o->how, L"партия 20 (по умолчанию: Настройки → Нормирование)");
  nm_route(&b, &r, NULL, L"норма: L 100, проходов 1, партия 5", &res);
  near("заданное важнее умолчания: t", nm_v(&res.op[0].c, L"t"), 2.5);
  near("заданная партия важнее", nm_v(&res.op[0].c, L"партия"), 5);
  lim_factory();
  /* припуск больше предела 20; t задана больше предела 8; проходов больше предела 10 — каждый глубже */
  tn_cpy(r.blank, TN_TXT, L"Круг 100 ГОСТ 2590"); /* h = 30 → 20 */
  nm_route(&b, &r, NULL, L"норма: L 100, глубина резания 12", &res);
  o = &res.op[0];
  near("припуск 30 — в пределе h 20", nm_v(&o->c, L"h"), 20);
  near("t в пределе 8", nm_v(&o->c, L"t"), 8);
  near("проходов 20/8 → 3", nm_v(&o->c, L"i"), 3);
  nm_route(&b, &r, NULL, L"норма: L 100, глубина резания 1", &res);
  o = &res.op[0];
  near("проходов не больше 10", nm_v(&o->c, L"i"), 10);
  near("t = h/10", nm_v(&o->c, L"t"), 2);
  lim_factory();
  nm_base_free(&b);
}

