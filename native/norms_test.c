static void base_fill(NmBase *b) {
  memset(b, 0, sizeof(*b));
  for (size_t i = 0; i < sizeof(kTabs) / sizeof(kTabs[0]); i++)
    if (!nm_base_add(b, dupw(kTabs[i][1]), kTabs[i][0])) {
      g_fail++;
      printf("FAIL таблица %zu не прочиталась: ", i);
      out8(b->err);
      printf("\n");
    }
}

