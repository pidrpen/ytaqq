static char *sample(size_t *len) {
  char *t = (char *)malloc(4000);
  int n = sprintf(t, "Обозначение\tНаименование\tКол-во\n");
  for (int i = 1; i < 40; i++) n += sprintf(t + n, "АБВГ.301000.%03d\tДеталь номер %d\t%d\n", i, i, i % 7 + 1);
  *len = (size_t)n;
  return t;
}

static void test_inflate(void) {
  size_t sl;
  char *s = sample(&sl);
  struct {
    const char *name;
    const unsigned char *d;
    size_t n;
  } st[] = {{"фиксированный код", kFixed, sizeof(kFixed)},
            {"динамический код", kDynamic, sizeof(kDynamic)},
            {"только Хаффман", kHuffOnly, sizeof(kHuffOnly)}};
  for (size_t i = 0; i < sizeof(st) / sizeof(st[0]); i++) {
    size_t ol = 0;
    unsigned char *o = xr_inflate(st[i].d, st[i].n, 0, &ol);
    ok(o && ol == sl && !memcmp(o, s, sl), st[i].name);
    free(o);
    /* обрезанный поток — не падать, а NULL */
    o = xr_inflate(st[i].d, st[i].n / 2, 0, &ol);
    ok(!o, "обрезанный поток — ошибка");
    free(o);
  }
  /* «store»: два блока, второй — последний */
  unsigned char *b = (unsigned char *)malloc(sl + 20);
  size_t h = sl / 2, k = 0;
  b[k++] = 0x00, b[k++] = (unsigned char)(h & 255), b[k++] = (unsigned char)(h >> 8);
  b[k++] = (unsigned char)(~h & 255), b[k++] = (unsigned char)((~h >> 8) & 255);
  memcpy(b + k, s, h), k += h;
  size_t r = sl - h;
  b[k++] = 0x01, b[k++] = (unsigned char)(r & 255), b[k++] = (unsigned char)(r >> 8);
  b[k++] = (unsigned char)(~r & 255), b[k++] = (unsigned char)((~r >> 8) & 255);
  memcpy(b + k, s + h, r), k += r;
  size_t ol = 0;
  unsigned char *o = xr_inflate(b, k, sl, &ol);
  ok(o && ol == sl && !memcmp(o, s, sl), "store");
  free(o);
  b[3] ^= 1; /* NLEN не дополнение LEN */
  o = xr_inflate(b, k, 0, &ol);
  ok(!o, "store: битая длина — ошибка");
  free(o);
  free(b);
  free(s);
}

/* ---- zip «store» в памяти ---- */

typedef struct {
  unsigned char *p;
  size_t n;
} Buf;

static void put(Buf *b, const void *d, size_t n) {
  b->p = (unsigned char *)realloc(b->p, b->n + n);
  memcpy(b->p + b->n, d, n);
  b->n += n;
}
static void u16(Buf *b, unsigned v) {
  unsigned char c[2] = {(unsigned char)v, (unsigned char)(v >> 8)};
  put(b, c, 2);
}
static void u32(Buf *b, unsigned long v) {
  unsigned char c[4] = {(unsigned char)v, (unsigned char)(v >> 8), (unsigned char)(v >> 16), (unsigned char)(v >> 24)};
  put(b, c, 4);
}

static Buf zip_store(const char *const *names, const char *const *data, int n) {
  Buf z = {0}, cd = {0};
  for (int i = 0; i < n; i++) {
    size_t off = z.n, nl = strlen(names[i]), dl = strlen(data[i]);
    u32(&z, 0x04034b50), u16(&z, 20), u16(&z, 0), u16(&z, 0), u16(&z, 0), u16(&z, 0), u32(&z, 0), u32(&z, dl), u32(&z, dl);
    u16(&z, (unsigned)nl), u16(&z, 0), put(&z, names[i], nl), put(&z, data[i], dl);
    u32(&cd, 0x02014b50), u16(&cd, 20), u16(&cd, 20), u16(&cd, 0), u16(&cd, 0), u16(&cd, 0), u16(&cd, 0), u32(&cd, 0);
    u32(&cd, dl), u32(&cd, dl), u16(&cd, (unsigned)nl), u16(&cd, 0), u16(&cd, 0), u16(&cd, 0), u16(&cd, 0), u32(&cd, 0);
    u32(&cd, off), put(&cd, names[i], nl);
  }
  size_t cdo = z.n;
  put(&z, cd.p, cd.n);
  u32(&z, 0x06054b50), u16(&z, 0), u16(&z, 0), u16(&z, (unsigned)n), u16(&z, (unsigned)n), u32(&z, cd.n), u32(&z, cdo), u16(&z, 0);
  free(cd.p);
  return z;
}

