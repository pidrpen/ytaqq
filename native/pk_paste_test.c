static void out8(const wchar_t *w) {
  for (; w && *w; w++) {
    unsigned c = (unsigned)*w;
    if (c < 0x80) putchar((int)c);
    else if (c < 0x800) { putchar(0xC0 | c >> 6); putchar(0x80 | (c & 63)); }
    else { putchar(0xE0 | c >> 12); putchar(0x80 | ((c >> 6) & 63)); putchar(0x80 | (c & 63)); }
  }
}

static int g_fail, g_n, g_verbose;
static const char *g_case;

/* что легло: строки «лист|ячейка|ячейка…» без пустых хвостов, одна под другой */
static wchar_t g_got[20000];
static const wchar_t *const kSheet[] = {L"И", L"С", L"О", L"З"};

static void put(void *ctx, int sheet, const wchar_t *const *c) {
  (void)ctx;
  int last = PP_COLS - 1;
  while (last > 0 && !c[last][0]) last--;
  wcscat(g_got, kSheet[sheet]);
  for (int i = 0; i <= last; i++) wcscat(g_got, L"|"), wcscat(g_got, c[i]);
  wcscat(g_got, L"\n");
}

static PpOut g_out;

static void run(const char *name, const wchar_t *text, int sheet, const wchar_t *asmb, const wchar_t *part) {
  g_case = name;
  g_got[0] = 0;
  PpIn in = {sheet, asmb, part, put, NULL};
  pp_parse(text, &in, &g_out);
  if (g_verbose) printf("== %s (how %d)\n", name, g_out.how), out8(g_got);
}

/* строка want есть среди того, что легло */
static void has(const wchar_t *want) {
  g_n++;
  wchar_t w[600];
  swprintf(w, 600, L"%ls\n", want);
  if (!wcsstr(g_got, w)) {
    g_fail++;
    printf("FAIL %s: нет строки «", g_case);
    out8(want);
    printf("»\n  легло:\n");
    out8(g_got);
  }
}

static void hasnt(const wchar_t *part) {
  g_n++;
  if (wcsstr(g_got, part)) {
    g_fail++;
    printf("FAIL %s: лишнее «", g_case);
    out8(part);
    printf("»\n");
  }
}

static void ok(int cond, const char *what) {
  g_n++;
  if (!cond) g_fail++, printf("FAIL %s: %s\n", g_case, what);
}

static void eqw(const wchar_t *got, const wchar_t *want, const char *what) {
  g_n++;
  if (wcscmp(got, want)) {
    g_fail++;
    printf("FAIL %s: «", what);
    out8(got);
    printf("», ждали «");
    out8(want);
    printf("»\n");
  }
}

