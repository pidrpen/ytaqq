static BOOL ac_policy_terms(const wchar_t *q, const wchar_t *const *terms, size_t n) {
  wchar_t lower[2000]; lstrcpynW(lower, q, 2000); CharLowerBuffW(lower, (DWORD)wcslen(lower));
  for (size_t i = 0; i < n; i++) if (wcsstr(lower, terms[i])) return TRUE;
  return FALSE;
}
static BOOL ac_policy_technical(const wchar_t *q) {
  const wchar_t *terms[] = {L"черт", L"техпро", L"тех про", L"технологич", L"гост", L"твёрд", L"тверд", L"закал", L"отпуск стал", L"режим резан", L"обработк", L"точени", L"фрезер", L"шлифов", L"сталь", L"стали", L"сплав"};
  return ac_policy_terms(q, terms, sizeof(terms) / sizeof(terms[0]));
}
static BOOL ac_policy_app(const wchar_t *q) {
  const wchar_t *terms[] = {L"cursorpad", L"курсор", L"что умеешь", L"твои инструменты", L"твои функции", L"как тебя", L"запомни:"};
  return ac_policy_terms(q, terms, sizeof(terms) / sizeof(terms[0]));
}
