typedef struct {
  unsigned recent[FJ_RECENT]; /* отпечатки последних реплик (fj_key) */
  int nRecent, at;
  int lastKind, kindRun;      /* сколько подряд реплик одного рода */
} FjState;

/* буква в нижний регистр без локали: кириллица, ё, латиница; не буква и не цифра — 0 */
static wchar_t fj_low(wchar_t c) {
  if (c >= 0x410 && c <= 0x42F) return (wchar_t)(c + 0x20);
  if (c == 0x401 || c == 0x451) return 0x435; /* ё → е */
  if (c >= 0x430 && c <= 0x44F) return c;
  if (c >= L'A' && c <= L'Z') return (wchar_t)(c + 32);
  if ((c >= L'a' && c <= L'z') || (c >= L'0' && c <= L'9')) return c;
  return 0;
}

/* отпечаток реплики: первые 48 букв и цифр без регистра — «Сталь 45…» и «сталь 45…» одно и то же */
static unsigned fj_key(const wchar_t *s) {
  unsigned h = 2166136261u;
  int n = 0;
  for (; *s && n < 48; s++) {
    wchar_t c = fj_low(*s);
    if (!c) continue;
    h = (h ^ (unsigned)c) * 16777619u;
    n++;
  }
  return n ? h | 1u : 0u;
}

static int fj_seen(const FjState *st, unsigned key) {
  for (int i = 0; i < st->nRecent; i++)
    if (st->recent[i] == key) return 1;
  return 0;
}

/* запомнить показанную реплику */
static void fj_note(FjState *st, const wchar_t *text, int joke) {
  unsigned key = fj_key(text);
  if (key && !fj_seen(st, key)) {
    st->recent[st->at] = key;
    st->at = (st->at + 1) % FJ_RECENT;
    if (st->nRecent < FJ_RECENT) st->nRecent++;
  }
  st->kindRun = st->lastKind == joke + 1 ? st->kindRun + 1 : 1;
  st->lastKind = joke + 1;
}

/* какой род рассказать: случайно, но не больше двух одинаковых подряд */
static int fj_kind(const FjState *st, unsigned r) {
  if (st->kindRun >= 2 && st->lastKind) return st->lastKind == 1 ? 1 : 0;
  return (int)((r >> 3) & 1);
}

/* строка списка рода joke (−1 — любого), которой не было среди последних; r — случайное число.
   Возвращает номер в kFjItems. Если все недавние — любая, кроме самой последней. */
static int fj_pick(const FjState *st, int joke, unsigned r) {
  int fresh[FJ_N], nf = 0, any[FJ_N], na = 0;
  unsigned last = st->nRecent ? st->recent[(st->at + FJ_RECENT - 1) % FJ_RECENT] : 0;
  for (int i = 0; i < FJ_N; i++) {
    if (joke >= 0 && kFjItems[i].joke != joke) continue;
    unsigned key = fj_key(kFjItems[i].text);
    if (!fj_seen(st, key)) fresh[nf++] = i;
    if (key != last) any[na++] = i;
  }
  if (nf) return fresh[r % (unsigned)nf];
  if (na) return any[r % (unsigned)na];
  return (int)(r % (unsigned)FJ_N);
}

